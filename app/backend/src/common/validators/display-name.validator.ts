/**
 * Безопасное отображаемое имя (workspace, server).
 *
 * Whitelist-подход вместо экранирования при хранении: разрешены только
 * буквы любых алфавитов, цифры, пробел и `-_#`. Всё остальное отклоняется
 * на границе, поэтому вредоносный код (`<script>`, кавычки, `;`, слеши,
 * смайлики) в принципе не может попасть в БД — экранировать при записи
 * нечего и не нужно (эскейпинг на запись портит данные и даёт двойное
 * экранирование; границы shell закрыты `shq()`, SQL — параметризацией Prisma).
 */
export const DISPLAY_NAME_PATTERN = /^[\p{L}\p{N} _#-]{1,64}$/u;

export const DISPLAY_NAME_MESSAGE =
  'name can contain only letters, numbers, spaces and - _ # (1-64 characters, no emoji)';
